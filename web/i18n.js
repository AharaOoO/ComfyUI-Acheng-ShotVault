export function getLang() {
  try {
    const saved = window.localStorage?.getItem(STORAGE_KEY);
    if (saved === "en" || saved === "zh") return saved;
    const comfyLocale = String(
      window.localStorage?.getItem("Comfy.Settings.Comfy.Locale") || ""
    ).replace(/^"|"$/g, "").trim().toLowerCase();
    if (comfyLocale) return comfyLocale.startsWith("zh") ? "zh" : "en";
    const navLang = String(window.navigator?.language || "").trim().toLowerCase();
    if (navLang) return navLang.startsWith("zh") ? "zh" : "en";
    return "zh";
  } catch {
    return "zh";
  }
}

export function pickOutdatedReasons(syncStatus) {
  if (!syncStatus || typeof syncStatus !== "object") return [];
  if (getLang() === "en" && Array.isArray(syncStatus.outdated_reasons_en) && syncStatus.outdated_reasons_en.length) {
    return syncStatus.outdated_reasons_en;
  }
  return Array.isArray(syncStatus.outdated_reasons) ? syncStatus.outdated_reasons : [];
}

export function setLang(lang) {
  const norm = lang === "en" ? "en" : "zh";
  try {
    window.localStorage?.setItem(STORAGE_KEY, norm);
  } catch {
    // ignore storage errors
  }
  window.dispatchEvent(new CustomEvent("acheng:lang-change", { detail: { lang: norm } }));
  return norm;
}

export function toggleLang() {
  return setLang(getLang() === "zh" ? "en" : "zh");
}

export function t(key, vars = null) {
  const lang = getLang();
  const table = DICT[lang] || DICT.zh;
  let str = table[key] ?? DICT.zh[key] ?? key;
  if (vars && typeof vars === "object") {
    for (const [k, v] of Object.entries(vars)) {
      str = str.replaceAll(`{${k}}`, String(v ?? ""));
    }
  }
  return str;
}

export function fmtBytes(bytes) {
  const n = Math.max(0, Number(bytes) || 0);
  if (n < 1024) return `${n} B`;
  if (n < 1024 * 1024) return `${(n / 1024).toFixed(1)} KB`;
  if (n < 1024 * 1024 * 1024) return `${(n / (1024 * 1024)).toFixed(1)} MB`;
  return `${(n / (1024 * 1024 * 1024)).toFixed(2)} GB`;
}
